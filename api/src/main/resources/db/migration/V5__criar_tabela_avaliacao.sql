-- Pesquisa de satisfação do Gerenciador de Tarefas (tela entregue em WebView para a squad parceira)
CREATE TABLE avaliacao (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nota_geral              INTEGER                  NOT NULL,
    facilidade_uso          INTEGER                  NOT NULL,
    recomendaria            BOOLEAN                  NOT NULL,
    funcionalidade_favorita VARCHAR(30),
    comentario              VARCHAR(500),
    criada_em               TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT ck_avaliacao_nota_geral CHECK (nota_geral BETWEEN 1 AND 5),
    CONSTRAINT ck_avaliacao_facilidade CHECK (facilidade_uso BETWEEN 1 AND 5),
    CONSTRAINT ck_avaliacao_funcionalidade CHECK (funcionalidade_favorita IN
        ('CADASTRO', 'EDICAO', 'BUSCA_FILTROS', 'DASHBOARD', 'HISTORICO', 'APP_CELULAR'))
);

CREATE INDEX idx_avaliacao_criada_em ON avaliacao (criada_em);
