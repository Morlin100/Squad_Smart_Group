-- HU05: histórico de alterações das tarefas.
-- Sem chave estrangeira de propósito: o histórico continua existindo depois que a tarefa é excluída.
CREATE TABLE tarefa_historico (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tarefa_id    BIGINT                   NOT NULL,
    acao         VARCHAR(20)              NOT NULL,
    detalhes     VARCHAR(2000),
    realizado_em TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT ck_historico_acao CHECK (acao IN ('CRIACAO', 'ATUALIZACAO', 'EXCLUSAO'))
);

CREATE INDEX idx_historico_tarefa ON tarefa_historico (tarefa_id);
