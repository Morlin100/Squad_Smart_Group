-- KAN-93: Planning Poker (rodada, participante e voto)
CREATE TABLE rodada (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tarefa       VARCHAR(150)             NOT NULL,
    situacao     VARCHAR(20)              NOT NULL,
    criada_em    TIMESTAMP WITH TIME ZONE NOT NULL,
    encerrada_em TIMESTAMP WITH TIME ZONE,
    CONSTRAINT ck_rodada_situacao CHECK (situacao IN ('ABERTA', 'ENCERRADA'))
);

CREATE TABLE participante (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rodada_id BIGINT      NOT NULL REFERENCES rodada (id) ON DELETE CASCADE,
    nome      VARCHAR(60) NOT NULL,
    CONSTRAINT uk_participante_rodada_nome UNIQUE (rodada_id, nome)
);

CREATE TABLE voto (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rodada_id       BIGINT                   NOT NULL REFERENCES rodada (id) ON DELETE CASCADE,
    participante_id BIGINT                   NOT NULL REFERENCES participante (id) ON DELETE CASCADE,
    carta           INTEGER                  NOT NULL,
    votado_em       TIMESTAMP WITH TIME ZONE NOT NULL,
    -- Garante no banco a regra de um voto por participante
    CONSTRAINT uk_voto_participante UNIQUE (participante_id),
    CONSTRAINT ck_voto_carta CHECK (carta IN (1, 2, 3, 5, 8, 13))
);

CREATE INDEX idx_voto_rodada ON voto (rodada_id);
