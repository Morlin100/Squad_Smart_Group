-- Módulo de cadastro de tarefas
CREATE TABLE tarefa (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titulo          VARCHAR(150)             NOT NULL,
    descricao       VARCHAR(1000),
    status          VARCHAR(20)              NOT NULL,
    prioridade      VARCHAR(20)              NOT NULL,
    data_vencimento DATE,
    criado_em       TIMESTAMP WITH TIME ZONE NOT NULL,
    atualizado_em   TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT ck_tarefa_status     CHECK (status IN ('PENDENTE', 'EM_ANDAMENTO', 'CONCLUIDA')),
    CONSTRAINT ck_tarefa_prioridade CHECK (prioridade IN ('BAIXA', 'MEDIA', 'ALTA'))
);

CREATE INDEX idx_tarefa_status ON tarefa (status);
CREATE INDEX idx_tarefa_data_vencimento ON tarefa (data_vencimento);
